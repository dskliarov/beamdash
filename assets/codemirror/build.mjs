import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
process.chdir(here);
const out = path.resolve(here, '../../priv/static/assets/vendor/codemirror');
await mkdir(out, { recursive: true });
const result = await build({
  entryPoints: ['editor.mjs'], bundle: true, minify: true, target: 'es2020', format: 'iife',
  globalName: 'BeamCodeMirror', outfile: path.join(out, 'editor.js'), metafile: true,
  legalComments: 'inline', banner: { js: '/* CodeMirror 6 module editor. Generated by assets/codemirror/build.mjs. See LICENSES.txt. */' },
});
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.startsWith('node_modules/')) continue;
  const parts = input.slice('node_modules/'.length).split('/');
  packages.add(parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0]);
}
const manifest = {};
const notices = [];
for (const name of [...packages].sort()) {
  const dir = path.join(here, 'node_modules', name);
  const pkg = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'));
  manifest[name] = { version: pkg.version, license: pkg.license };
  let license;
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md']) {
    try { license = await readFile(path.join(dir, file), 'utf8'); break; } catch (_) {}
  }
  if (!license) {
    const readme = await readFile(path.join(dir, 'README.md'), 'utf8');
    license = readme.slice(readme.search(/^##? License/m));
  }
  notices.push(`${name} ${pkg.version} (${pkg.license})\n${license}`);
}
await writeFile(path.join(out, 'LICENSES.txt'), notices.join('\n\n' + '='.repeat(72) + '\n\n') + '\n');
await writeFile(path.join(out, 'versions.json'), JSON.stringify(manifest, null, 2) + '\n');
